import { api, ExperimentRow } from '../api';
import { ErrorBox, useLoader } from './useLoader';

const CAPTIONS: Record<string, string> = {
  'cicids2017_binary_precision_recall.png': 'Precision-recall curves, binary detection, every model on the same test rows.',
  'cicids2017_binary_roc_all_models.png': 'ROC curves, binary detection, every model on the same test rows.',
  'cicids2017_binary_model_comparison.png': 'F1, MCC, false-positive and false-negative rates of each binary model.',
  'cicids2017_known_vs_unseen.png': 'Each attack type held out of supervised training, against the autoencoder.',
  'cicids2017_ablation_detection.png': 'Ablation: detection with and without each component.',
  'cicids2017_shap_summary.png': 'SHAP summary of the binary XGBoost detector on sampled test flows.',
  'cicids2017_anomaly_score_distribution.png': 'Autoencoder reconstruction error, benign vs attack, on the test split.',
};

const NUMERIC = [
  'accuracy', 'precision', 'recall', 'macro_f1', 'weighted_f1', 'mcc', 'fpr', 'fnr', 'roc_auc',
  'training_time_s', 'inference_time_ms_per_row',
];

const fmt = (v: string | number | null) => (v === null || v === '' ? '—' : typeof v === 'number' ? v.toFixed(4) : v);

export function ResearchTab() {
  const experiments = useLoader(api.experiments);
  const figures = useLoader(api.figures);

  if (experiments.error) return <ErrorBox message={experiments.error} />;

  return (
    <>
      <div className="card">
        <h2>Experiments</h2>
        <p>
          One row per model and test split, written from the saved metric files by <code>src.evaluation.tracker</code>. An empty
          cell means the value was not measured for that run. Binary metrics treat ATTACK as the positive class.
        </p>
        {!experiments.data && !experiments.error && <p className="muted">Loading…</p>}
        {experiments.data && (
          <div className="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Dataset</th>
                  <th>Model</th>
                  <th>Task</th>
                  {NUMERIC.map((c) => (
                    <th key={c} className="num">
                      {c.replace(/_/g, ' ')}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {experiments.data.map((row, i) => (
                  <tr key={`${row.experiment_id}-${i}`}>
                    <td>{row.dataset}</td>
                    <td>{row.model}</td>
                    <td>{row.task}</td>
                    {NUMERIC.map((c) => (
                      <td key={c} className="num">
                        {fmt(row[c] ?? null)}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>

      <div className="card">
        <h2>Figures</h2>
        <p className="muted">Every figure is drawn from saved results. Figures are regenerated by the research scripts; none is hand-made.</p>
        {figures.error && <ErrorBox message={figures.error} />}
        {figures.data && figures.data.length === 0 && <p className="muted">No figures saved yet.</p>}
        <div className="figures">
          {figures.data?.map((name) => (
            <figure key={name} style={{ margin: 0 }}>
              <img src={api.figureUrl(name)} alt={name} />
              <figcaption className="muted" style={{ marginTop: '0.4rem' }}>
                {CAPTIONS[name] ?? name}
              </figcaption>
            </figure>
          ))}
        </div>
      </div>
    </>
  );
}
