def test_identifier_columns_are_dropped_and_leaky_feature_is_flagged():
    rng = np.random.default_rng(0)
    n = 4000
    y = rng.integers(0, 2, size=n)
    X = pd.DataFrame({
        "Flow ID": [f"id{i}" for i in range(n)],
        "Source IP": ["10.0.0.1"] * n,
        "Flow Duration": rng.normal(size=n),
        "target_proxy": y.astype(float),
    })
    X_clean, dropped = drop_identifier_columns(X)
    assert set(dropped) == {"Flow ID", "Source IP"}
    assert list(X_clean.columns) == ["Flow Duration", "target_proxy"]

    scan = single_feature_leakage_scan(X_clean, y, sample_size=None, threshold=0.99)
    flagged = scan.loc[scan["flagged"], "feature"].tolist()
    assert flagged == ["target_proxy"]


def test_preprocessing_statistics_come_from_training_rows_only():
    """The imputation/scaling centre must equal the TRAIN median, not the median over all rows."""
    n = 300
    x = np.arange(n, dtype=float)
    x[200:] += 10_000  # test-like rows far away: full-data median differs noticeably from train median
    y = np.tile([0, 1, 0], n // 3 + 1)[:n]
    X = pd.DataFrame({"feat_a": x, "feat_b": np.sin(np.arange(n))})
    y_multi = pd.Series(np.where(y == 1, "DoS Hulk", "BENIGN"))
    pipe = CyberthreatPreprocessingPipeline(test_size=0.2, val_size=0.1, random_state=42)
    pipe.fit_transform_splits(X, pd.Series(y), y_multi)

    # Recreate exactly the training split the pipeline used (same inputs, same seed).
    X_train_raw, _, _, _ = train_test_split(
        X, pd.Series(y), test_size=pipe.test_size + pipe.val_size, stratify=pd.Series(y), random_state=42
    )
    train_median = X_train_raw["feat_a"].median()
    full_median = X["feat_a"].median()
    assert not np.isclose(train_median, full_median)

    centre = pipe.scaler.scaler_.center_[pipe.scaler.numeric_cols_.index("feat_a")]
    assert np.isclose(centre, train_median)


def test_sample_positions_stratified_cap_keeps_proportions_and_is_reproducible():
    strata = np.array([0] * 900 + [1] * 90 + [2] * 10)
    pos_a, meta = sample_positions(strata, strategy="stratified", max_rows=200, seed=7)
    pos_b, _ = sample_positions(strata, strategy="stratified", max_rows=200, seed=7)
    assert len(pos_a) == 200 and meta["method"] == "stratified_cap"
    assert np.array_equal(pos_a, pos_b)
    kept = np.bincount(strata[pos_a], minlength=3)
    assert kept[2] >= 1  # the rare class is not dropped
    assert abs(kept[0] / 200 - 0.9) < 0.02


def test_sample_positions_none_and_uncapped_keep_every_row():
    strata = np.array([0, 0, 1, 1, 1])
    pos, meta = sample_positions(strata, strategy="none", max_rows=2)
    assert len(pos) == 5 and meta["method"] == "all_rows"
    pos, _ = sample_positions(strata, strategy="stratified", max_rows=None)
    assert len(pos) == 5


def test_sample_positions_falls_back_when_a_class_has_one_member():
    strata = np.array([0] * 50 + [1] * 49 + [2])
    pos, meta = sample_positions(strata, strategy="stratified", max_rows=30, seed=1)
    assert len(pos) == 30 and meta["method"] == "uniform_random_cap"


def test_binary_metrics_match_hand_computed_values():
    y_true = np.array([0, 0, 1, 1])
    y_pred = np.array([0, 1, 1, 1])
