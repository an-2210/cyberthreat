def test_saved_detectors_predict_consistently_on_raw_rows(tmp_path, synthetic_raw_dir):
    """Saved artifacts load through CICIDS2017Detector and expose consistent predict/predict_proba."""
    from src.data.dataset_adapters import CICIDS2017Adapter
    from src.models.inference import CICIDS2017Detector

    cfg = load_config("configs/config.yaml")
    cfg["models"]["baselines"]["random_forest"]["n_estimators"] = 8
    cfg["models"]["advanced"]["xgboost"]["n_estimators"] = 8
    models_dir = tmp_path / "models"
    summary = run_pipeline(
        cfg,
        raw_dir=str(synthetic_raw_dir),
        results_dir=str(tmp_path / "results"),
        models_dir=str(models_dir),
        max_train_rows=250,
        data_source=SYNTHETIC_SOURCE,
    )
    raw = CICIDS2017Loader(synthetic_raw_dir).load_merged_dataset()
    X_raw, _, _ = CICIDS2017Adapter("Label").extract_labels(raw)  # raw feature columns, no label

    for task in ("binary", "multiclass"):
        for name in ("random_forest", "xgboost"):
            det = CICIDS2017Detector.load(task, name, artifacts_dir=models_dir)
            proba = det.predict_proba(X_raw.head(50))
            labels = det.predict(X_raw.head(50))
            assert proba.shape == (50, len(det.labels))
            assert np.allclose(proba.sum(axis=1), 1.0, atol=1e-6)
            assert (labels == np.asarray(det.labels)[proba.argmax(axis=1)]).all()

    binary = CICIDS2017Detector.load("binary", "xgboost", artifacts_dir=models_dir)
    assert binary.labels == ["BENIGN", "ATTACK"]
    multi = CICIDS2017Detector.load("multiclass", "random_forest", artifacts_dir=models_dir)
    assert multi.labels == summary["class_names"]
    with pytest.raises(ValueError, match="missing"):
        binary.predict(X_raw.drop(columns=[X_raw.columns[0]]))


