    assert report["missing_values"]["total_missing_cells"] > 0
    assert report["duplicate_rows_exact_including_label"]["count"] >= 5
    assert report["unexpected_label_values"] == []
    assert set(result["class_composition"].index) == {p.name for p in synthetic_raw_dir.iterdir()}
    assert result["class_distribution"]["count"].sum() == report["n_rows"]


